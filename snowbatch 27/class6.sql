SELECT
    A.MATCH_ID AS MATCH_1,
    A.TEAM1 AS TEAM_1,
    A.TEAM2 AS TEAM_2,
    B.MATCH_ID AS MATCH_2
FROM IPL_MATCHES A
JOIN IPL_MATCHES B
    ON A.TEAM1 = B.TEAM1
   AND A.TEAM2 = B.TEAM2
WHERE A.MATCH_ID < B.MATCH_ID;

SELECT
    A.MATCH_ID AS MATCH_1,
    A.TEAM1 AS TEAM_1,
    A.TEAM2 AS TEAM_2,
    B.MATCH_ID AS MATCH_2,
    B.TEAM1 AS TEAM_1_AGAIN,
    B.TEAM2 AS TEAM_2_AGAIN
FROM IPL_MATCHES A
JOIN IPL_MATCHES B
    ON (
        A.TEAM1 = B.TEAM1
        AND A.TEAM2 = B.TEAM2
    )
    OR (
        A.TEAM1 = B.TEAM2
        AND A.TEAM2 = B.TEAM1
    )
WHERE A.MATCH_ID < B.MATCH_ID;

SELECT
    A.MATCH_ID AS MATCH_1,
    A.VENUE,
    B.MATCH_ID AS MATCH_2
FROM IPL_MATCHES A
JOIN IPL_MATCHES B
    ON A.VENUE = B.VENUE
WHERE A.MATCH_ID < B.MATCH_ID;

SELECT
    A.MATCH_ID AS MATCH_1,
    A.SEASON,
    B.MATCH_ID AS MATCH_2
FROM IPL_MATCHES A
JOIN IPL_MATCHES B
    ON A.SEASON = B.SEASON
WHERE A.MATCH_ID < B.MATCH_ID;

SELECT
    A.MATCH_ID AS MATCH_1,

    SELECT
    A.MATCH_ID,
    A.TEAM1,
    A.TEAM2,
    B.MATCH_ID AS OTHER_MATCH_ID
FROM IPL_MATCHES A
JOIN IPL_MATCHES B
    ON A.TEAM1 = B.TEAM1
    OR A.TEAM2 = B.TEAM2
WHERE A.MATCH_ID < B.MATCH_ID
  AND (
      A.TEAM1 = 'CSK'
      OR A.TEAM2 = 'CSK'
  );
    A.WINNER,
    B.MATCH_ID AS MATCH_2
FROM IPL_MATCHES A
JOIN IPL_MATCHES B
    ON A.WINNER = B.WINNER
WHERE A.MATCH_ID < B.MATCH_ID;

SELECT
    A.MATCH_ID AS MATCH_1,
    A.MATCH_DATE,
    B.MATCH_ID AS MATCH_2
FROM IPL_MATCHES A
JOIN IPL_MATCHES B
    ON A.MATCH_DATE = B.MATCH_DATE
WHERE A.MATCH_ID < B.MATCH_ID;

-- Difference in seconds
SELECT DATEDIFF(
    SECOND,
    '2024-03-22 10:30:00'::TIMESTAMP,
    '2024-03-22 12:45:30'::TIMESTAMP
) AS SECONDS_DIFF;

-- Difference in minutes
SELECT DATEDIFF(
    MINUTE,
    '2024-03-22 10:30:00'::TIMESTAMP,
    '2024-03-22 12:45:30'::TIMESTAMP
) AS MINUTES_DIFF;

-- Difference in hours
SELECT DATEDIFF(
    HOUR,
    '2023-03-22 10:30:00'::TIMESTAMP,
    '2024-03-22 12:45:30'::TIMESTAMP
) AS HOURS_DIFF;

-- Difference in days
SELECT DATEDIFF(
    DAY,
    '2024-03-22 10:30:00'::TIMESTAMP,
    '2024-03-23 12:45:30'::TIMESTAMP
) AS DAYS_DIFF;
